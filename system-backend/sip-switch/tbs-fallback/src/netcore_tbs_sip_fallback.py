def render_pbx_registration(cfg: dict[str, Any]) -> str:
    pbx = cfg["fallback_pbx"]
    n = names(cfg)
    host = str(pbx["host"])
    port = int(pbx.get("port", 5060))
    username = str(pbx.get("username") or pbx.get("auth_username") or pbx.get("from_user") or "").strip()
    if not username:
        raise ValueError("fallback_pbx.username or from_user is required for registration failover")
    auth_user = str(pbx.get("auth_username") or username).strip()
    password = str(pbx.get("password") or "")
    expiration = int(pbx.get("registration_expiration_secs", 30))
    lines = [
        "; Phase 11c PBX DIRECT registration. Loaded only in confirmed fallback mode.",
        f"[{n['pbx_reg']}]",
        "type=registration",
        "transport=netcore-tbs-transport",
    ]
    if auth_user and password:
        lines.append(f"outbound_auth={n['pbx_auth']}")
    lines += [
        f"server_uri=sip:{host}:{port}",
        f"client_uri=sip:{username}@{host}",
        f"contact_user={pbx.get('contact_user') or username}",
        "retry_interval=5",
        "forbidden_retry_interval=30",
        "fatal_retry_interval=30",
        "max_retries=0",
        f"expiration={expiration}",
        f"endpoint={n['pbx_ep']}",
        "",
    ]
    return "\n".join(lines)


def render_active_registration(cfg: dict[str, Any], mode: str) -> str:
    failover = cfg["failover"]
    if mode == "central":
        target = Path(failover["central_registration_file"]).name
    elif mode == "pbx_direct":
        target = Path(failover["pbx_registration_file"]).name
    else:
        raise ValueError(f"invalid registration mode: {mode}")
    return f"; Phase 11c mutually exclusive active registration: {mode}\n#include {target}\n"


def render_extensions(cfg: dict[str, Any]) -> str:
    asterisk = cfg["asterisk"]
    central = cfg["central"]
    pbx = cfg["fallback_pbx"]
    routing = cfg["routing"]
    n = names(cfg)
    cto = int(asterisk.get("central_dial_timeout_secs", 60))
    pto = int(asterisk.get("fallback_dial_timeout_secs", 60))
    tto = int(asterisk.get("tetra_dial_timeout_secs", 35))
    prefix = str(routing.get("fallback_tetra_prefix", ""))
    strip = b(routing.get("strip_fallback_tetra_prefix", False))
    lines = [
        "; Generated by NetCore-TETRA Phase 11c. Do not edit manually.",
        "[netcore-from-native-tbs]",
        "exten => _X!,1,NoOp(NetCore TBS -> Telefonie ${EXTEN}; central Vermittlung mit exklusivem PBX-Fallback)",
        " same => n,Set(__NETCORE_SIP_ROUTE=central)",
        f" same => n,Dial(PJSIP/${{EXTEN}}@{n['central_ep']},{cto})",
    ]
    if b(routing.get("fallback_on_chanunavail", True), True):
        lines += [" same => n,GotoIf($[\"${DIALSTATUS}\"=\"CHANUNAVAIL\"]?consider-fallback)"]
    if b(routing.get("fallback_on_congestion", True), True):
        lines += [" same => n,GotoIf($[\"${DIALSTATUS}\"=\"CONGESTION\"]?consider-fallback)"]
    lines += [
        " same => n,Goto(done)",
        " same => n(consider-fallback),GotoIf($[\"${DB(netcore/failover_mode)}\"=\"pbx_direct\"]?fallback:central-not-confirmed-down)",
        " same => n(central-not-confirmed-down),Set(DIALSTATUS=CHANUNAVAIL)",
        " same => n,Goto(done)",
        " same => n(fallback),Set(__NETCORE_SIP_ROUTE=direct-pbx-fallback)",
        f" same => n,Dial(PJSIP/${{EXTEN}}@{n['pbx_ep']},{pto})",
        " same => n(done),Hangup()",
        "",
        "[netcore-from-central-switch]",
        "exten => _X!,1,NoOp(NetCore central SIP Switch -> local TBS ${EXTEN})",
        f" same => n,Set(NETCORE_TBS_CONTACTS=${{PJSIP_DIAL_CONTACTS({n['native']},{n['native']},${{EXTEN}})}})",
        " same => n,GotoIf($[\"${NETCORE_TBS_CONTACTS}\"=\"\"]?unavailable)",
        f" same => n,Dial(${{NETCORE_TBS_CONTACTS}},{tto})",
        " same => n,Hangup()",
        " same => n(unavailable),Congestion(5)",
        "",
        "[netcore-from-pbx-fallback]",
        "exten => _X!,1,NoOp(NetCore direct PBX fallback -> local TBS ${EXTEN})",
        " same => n,GotoIf($[\"${DB(netcore/failover_mode)}\"=\"pbx_direct\"]?fallback-active:fallback-blocked)",
        " same => n(fallback-blocked),Hangup(21)",
        " same => n(fallback-active),NoOp(Confirmed PBX_DIRECT_ACTIVE)",
    ]
    if not b(routing.get("accept_direct_pbx_fallback", True), True):
        lines += [" same => n,Hangup(21)"]
    else:
        if prefix:
            lines += [
                f" same => n,GotoIf($[\"${{EXTEN:0:{len(prefix)}}}\"=\"{prefix}\"]?prefixok:badprefix)",
                " same => n(prefixok),NoOp(Fallback prefix accepted)",
            ]
            lines += [f" same => n,Set(NETCORE_TETRA_NUMBER=${{EXTEN:{len(prefix)}}})" if strip else " same => n,Set(NETCORE_TETRA_NUMBER=${EXTEN})"]
            lines += [" same => n,Goto(deliver)", " same => n(badprefix),Hangup(21)"]
        else:
            lines += [" same => n,Set(NETCORE_TETRA_NUMBER=${EXTEN})"]
        lines += [
            f" same => n(deliver),Set(NETCORE_TBS_CONTACTS=${{PJSIP_DIAL_CONTACTS({n['native']},{n['native']},${{NETCORE_TETRA_NUMBER}})}})",
            " same => n,GotoIf($[\"${NETCORE_TBS_CONTACTS}\"=\"\"]?unavailable)",
            f" same => n,Dial(${{NETCORE_TBS_CONTACTS}},{tto})",
            " same => n,Hangup()",
            " same => n(unavailable),Congestion(5)",
        ]
    return "\n".join(lines).rstrip() + "\n"


