def default_state(cfg: dict[str, Any]) -> dict[str, Any]:
    mode = str(cfg["failover"].get("default_mode", "central"))
    return {
        "schema": "netcore-tbs-sip-failover-state-v1",
        "node_id": cfg["service"]["node_id"],
        "mode": mode,
        "phase": "CENTRAL_ACTIVE" if mode == "central" else "PBX_DIRECT_ACTIVE",
        "central_failures": 0,
        "central_recovery_since": None,
        "last_transition_at": None,
        "last_probe_at": None,
        "last_probe_ok": None,
        "last_reason": "initial",
    }


def read_state(cfg: dict[str, Any]) -> dict[str, Any]:
    path = Path(cfg["failover"]["state_file"])
    if not path.exists():
        return default_state(cfg)
    try:
        data = json.loads(path.read_text(encoding="utf-8"))
        if data.get("mode") not in {"central", "pbx_direct"}:
            return default_state(cfg)
        return {**default_state(cfg), **data}
    except Exception:
        return default_state(cfg)


class AsteriskCLI:
    def __init__(self, binary: str):
        self.binary = binary

    def run(self, command: str, check: bool = False) -> subprocess.CompletedProcess[str]:
        proc = subprocess.run([self.binary, "-rx", command], text=True, capture_output=True)
        if check and proc.returncode:
            raise RuntimeError((proc.stderr or proc.stdout or command).strip())
        return proc

    def reload_registrations(self) -> None:
        proc = self.run("module reload res_pjsip_outbound_registration.so")
        if proc.returncode:
            self.run("core reload", check=True)

    def unregister(self, registration_id: str) -> None:
        self.run(f"pjsip send unregister {registration_id}")

    def set_mode_db(self, mode: str) -> None:
        self.run(f"database put netcore failover_mode {mode}", check=True)

    def registration_status(self, registration_id: str) -> str:
        proc = self.run("pjsip show registrations")
        if proc.returncode:
            return "unknown"
        for line in proc.stdout.splitlines():
            if registration_id in line:
                low = line.lower()
                if "registered" in low and "unregistered" not in low:
                    return "registered"
                if "rejected" in low:
                    return "rejected"
                if "unregistered" in low:
                    return "unregistered"
                return line.strip()
        return "absent"

    def aor_available(self, aor_id: str) -> bool:
        proc = self.run(f"pjsip show aor {aor_id}")
        if proc.returncode:
            return False
        text = proc.stdout.lower()
        if re.search(r"\bavail\b", text) and "unavail" not in text:
            return True
        if "status" in text and "available" in text and "unavailable" not in text:
            return True
        return False


class FailoverController:
    def __init__(self, cfg_path: Path, cli: AsteriskCLI | Any, sleeper=time.sleep):
        self.cfg_path = cfg_path
        self.cfg = load(cfg_path)
        ensure(self.cfg)
        self.cli = cli
        self.sleeper = sleeper
        self.n = names(self.cfg)
        self.state = read_state(self.cfg)
        self.stop_requested = False

    @property
    def state_path(self) -> Path:
        return Path(self.cfg["failover"]["state_file"])

    @property
    def active_file(self) -> Path:
        return Path(self.cfg["failover"]["active_registration_file"])

    def save(self) -> None:
        atomic_json(self.state_path, self.state)

    def switch_mode(self, target: str, reason: str, now: float | None = None) -> None:
        if target not in {"central", "pbx_direct"}:
            raise ValueError(target)
        now = time.time() if now is None else now
        current = self.state.get("mode", "central")
        if current == target and self.active_file.exists():
            self.cli.set_mode_db(target)
            return
        if current == "pbx_direct" and target == "central":
            self.state["phase"] = "RECOVERY_PENDING"
            self.save()
            self.cli.unregister(self.n["pbx_reg"])
            self.sleeper(float(self.cfg["failover"].get("unregister_grace_secs", 2)))
        elif current == "central" and target == "pbx_direct":
            self.state["phase"] = "FAILOVER_PENDING"
            self.save()
            self.cli.unregister(self.n["central_reg"])
        atomic_write(self.active_file, render_active_registration(self.cfg, target), 0o640)
        self.cli.reload_registrations()
        self.cli.set_mode_db(target)
        self.state.update({
            "mode": target,
            "phase": "CENTRAL_ACTIVE" if target == "central" else "PBX_DIRECT_ACTIVE",
            "central_failures": 0,
            "central_recovery_since": None,
            "last_transition_at": now,
            "last_reason": reason,
        })
        self.save()

    def central_probe(self) -> tuple[bool, dict[str, Any]]:
        aor_ok = self.cli.aor_available(self.n["central_aor"])
        reg_status = self.cli.registration_status(self.n["central_reg"])
        mode = self.state.get("mode")
        if mode == "central":
            healthy = aor_ok and reg_status == "registered"
        else:
            healthy = aor_ok
        return healthy, {"aor_available": aor_ok, "central_registration": reg_status}

    def tick(self, now: float | None = None) -> dict[str, Any]:
        now = time.time() if now is None else now
        healthy, detail = self.central_probe()
        self.state["last_probe_at"] = now
        self.state["last_probe_ok"] = healthy
        self.state["last_probe"] = detail
        mode = self.state.get("mode", "central")
        fail = self.cfg["failover"]
        threshold = max(1, int(fail.get("failure_threshold", 3)))
        recovery_secs = max(0.0, float(fail.get("recovery_stable_secs", 30)))

        if mode == "central":
            registration_grace = max(0.0, float(fail.get("central_registration_grace_secs", 15)))
            transitioned = self.state.get("last_transition_at")
            in_registration_grace = transitioned is not None and now - float(transitioned) < registration_grace
            if healthy:
                self.state["central_failures"] = 0
                self.state["phase"] = "CENTRAL_ACTIVE"
            elif in_registration_grace:
                self.state["central_failures"] = 0
                self.state["phase"] = "RECOVERY_PENDING"
            else:
                self.state["central_failures"] = int(self.state.get("central_failures", 0)) + 1
                self.state["phase"] = "FAILOVER_PENDING"
                if self.state["central_failures"] >= threshold:
                    self.switch_mode("pbx_direct", "central_unreachable_confirmed", now)
        else:
            if healthy:
                since = self.state.get("central_recovery_since")
                if since is None:
                    self.state["central_recovery_since"] = now
                    self.state["phase"] = "RECOVERY_PENDING"
                elif now - float(since) >= recovery_secs:
                    self.switch_mode("central", "central_stable_recovered", now)
            else:
                self.state["central_recovery_since"] = None
                self.state["phase"] = "PBX_DIRECT_ACTIVE"
        self.save()
        return dict(self.state)

    def run(self) -> None:
        fail = self.cfg["failover"]
        interval = max(1.0, float(fail.get("check_interval_secs", 2)))
        grace = max(0.0, float(fail.get("startup_grace_secs", 10)))
        self.cli.set_mode_db(str(self.state.get("mode", "central")))
        if grace:
            self.sleeper(grace)
        while not self.stop_requested:
            try:
                state = self.tick()
                print(json.dumps({"mode": state["mode"], "phase": state["phase"], "probe": state.get("last_probe")}), flush=True)
            except Exception as exc:
                print(f"failover tick error: {exc}", file=sys.stderr, flush=True)
            self.sleeper(interval)


def render(cfg_path: Path) -> dict[str, Any]:
    cfg = load(cfg_path)
    ensure(cfg)
    out = Path(cfg["asterisk"].get("config_dir", "/etc/asterisk"))
    fail = cfg["failover"]
    state = read_state(cfg)
    files = {
        out / "netcore-tbs-fallback-pjsip.conf": render_pjsip_base(cfg),
        out / "netcore-tbs-fallback-extensions.conf": render_extensions(cfg),
        out / "netcore-tbs-fallback-rtp.conf": render_rtp(cfg),
        Path(fail["central_registration_file"]): render_central_registration(cfg),
        Path(fail["pbx_registration_file"]): render_pbx_registration(cfg),
        Path(fail["active_registration_file"]): render_active_registration(cfg, str(state["mode"])),
        Path(cfg["asterisk"].get("native_snippet_file", "/etc/netcore/tbs-asterisk-local-snippet.toml")): render_native_snippet(cfg),
    }
    for path, content in files.items():
        atomic_write(path, content, 0o640 if path.suffix in {".conf", ".toml"} else None)
    return {"rendered": [str(path) for path in files], "node_id": cfg["service"]["node_id"], "active_mode": state["mode"]}


def status(cfg_path: Path) -> dict[str, Any]:
    cfg = load(cfg_path)
    ensure(cfg)
    cli = AsteriskCLI(str(cfg["asterisk"].get("binary", "/usr/sbin/asterisk")))
    n = names(cfg)
    state = read_state(cfg)
    active_path = Path(cfg["failover"]["active_registration_file"])
    commands = {
        "version": "core show version",
        "registrations": "pjsip show registrations",
        "contacts": "pjsip show contacts",
        "channels": "core show channels concise",
        "astdb_mode": "database get netcore failover_mode",
    }
    result: dict[str, Any] = {
        "node_id": cfg["service"]["node_id"],
        "state": state,
        "central_aor_available": cli.aor_available(n["central_aor"]),
        "central_registration": cli.registration_status(n["central_reg"]),
        "pbx_direct_registration": cli.registration_status(n["pbx_reg"]),
        "active_registration_include": active_path.read_text(encoding="utf-8").strip() if active_path.exists() else None,
        "asterisk": {},
    }
    for key, command in commands.items():
        proc = cli.run(command)
        result["asterisk"][key] = {"ok": proc.returncode == 0, "output": (proc.stdout or proc.stderr).strip()}
    return result


def acquire_lock(path: Path):
    path.parent.mkdir(parents=True, exist_ok=True)
    handle = path.open("w")
    try:
        fcntl.flock(handle.fileno(), fcntl.LOCK_EX | fcntl.LOCK_NB)
    except BlockingIOError as exc:
        handle.close()
        raise RuntimeError("another failover controller is already running") from exc
    handle.write(str(os.getpid()))
    handle.flush()
    return handle


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--config", default="/etc/netcore/tbs-sip-fallback.toml")
    parser.add_argument("--render", action="store_true")
    parser.add_argument("--status", action="store_true")
    parser.add_argument("--watch", action="store_true")
    parser.add_argument("--once", action="store_true")
    parser.add_argument("--force-mode", choices=["central", "pbx_direct"])
    args = parser.parse_args()
    path = Path(args.config)
    try:
        if args.render:
            print(json.dumps(render(path), indent=2))
            return 0
        if args.status:
            print(json.dumps(status(path), indent=2))
            return 0
        cfg = load(path)
        ensure(cfg)
        cli = AsteriskCLI(str(cfg["asterisk"].get("binary", "/usr/sbin/asterisk")))
        controller = FailoverController(path, cli)
        if args.force_mode:
            controller.switch_mode(args.force_mode, "manual_force")
            print(json.dumps(controller.state, indent=2))
            return 0
        if args.once:
            print(json.dumps(controller.tick(), indent=2))
            return 0
        if args.watch:
            lock = acquire_lock(Path(cfg["failover"]["lock_file"]))
            def stop(_signum, _frame):
                controller.stop_requested = True
            signal.signal(signal.SIGTERM, stop)
            signal.signal(signal.SIGINT, stop)
            try:
                controller.run()
            finally:
                lock.close()
            return 0
        parser.error("choose --render, --status, --watch, --once or --force-mode")
    except Exception as exc:
        print(f"error: {exc}", file=sys.stderr)
        return 1


if __name__ == "__main__":
    raise SystemExit(main())
