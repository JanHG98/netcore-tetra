def b(value: Any, default: bool = False) -> bool:
    if isinstance(value, bool):
        return value
    if value is None:
        return default
    return str(value).strip().lower() in {"1", "true", "yes", "on"}


def sid(value: Any) -> str:
    text = re.sub(r"[^a-zA-Z0-9_.:-]+", "-", str(value or "").strip()).strip("-")
    return text or "netcore"


def q(value: Any) -> str:
    return str(value or "").replace("\\", "\\\\").replace('"', '\\"')


def load(path: Path) -> dict[str, Any]:
    with path.open("rb") as handle:
        return tomllib.load(handle)


def atomic_write(path: Path, content: str, mode: int | None = None) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    tmp = path.with_name(path.name + ".tmp")
    tmp.write_text(content, encoding="utf-8")
    if mode is not None:
        os.chmod(tmp, mode)
    tmp.replace(path)


def atomic_json(path: Path, data: dict[str, Any]) -> None:
    atomic_write(path, json.dumps(data, indent=2, sort_keys=True) + "\n", 0o640)


def names(cfg: dict[str, Any]) -> dict[str, str]:
    node = sid(cfg["service"]["node_id"]).lower()
    return {
        "node": node,
        "native": sid(cfg["native_tbs"]["username"]),
        "central_ep": f"netcore-central-{node}",
        "central_auth": f"netcore-central-{node}-auth",
        "central_aor": f"netcore-central-{node}-aor",
        "central_reg": f"netcore-central-{node}-registration",
        "pbx_ep": f"netcore-pbx-fallback-{node}",
        "pbx_auth": f"netcore-pbx-fallback-{node}-auth",
        "pbx_aor": f"netcore-pbx-fallback-{node}-aor",
        "pbx_reg": f"netcore-pbx-fallback-{node}-registration",
    }


def ensure(cfg: dict[str, Any]) -> None:
    required = [
        ("service.node_id", cfg.get("service", {}).get("node_id")),
        ("native_tbs.username", cfg.get("native_tbs", {}).get("username")),
        ("central.host", cfg.get("central", {}).get("host")),
        ("central.username", cfg.get("central", {}).get("username")),
        ("fallback_pbx.host", cfg.get("fallback_pbx", {}).get("host")),
    ]
    missing = [name for name, value in required if not str(value or "").strip()]
    if missing:
        raise ValueError("missing required values: " + ", ".join(missing))
    mode = str(cfg.get("fallback_pbx", {}).get("mode", "registration")).lower()
    if mode != "registration":
        raise ValueError("Phase 11c requires fallback_pbx.mode = registration")
    if str(cfg.get("failover", {}).get("default_mode", "central")) not in {"central", "pbx_direct"}:
        raise ValueError("failover.default_mode must be central or pbx_direct")


